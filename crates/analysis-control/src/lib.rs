//! Cooperative cancellation shared by an operation owner and its worker.
//!
//! A default token is disabled. Scopes are thread-specific and restore the
//! previous token during unwinding as well as normal return. Captured tokens
//! keep their identity after the scope ends; cancellation never resets them.

use std::sync::{
    Arc, Mutex,
    atomic::{AtomicBool, Ordering},
};
use std::thread::ThreadId;

/// One-way cancellation signal; cloning shares the original operation.
#[derive(Clone, Debug, Default)]
pub struct Cancellation {
    cancelled: Option<Arc<AtomicBool>>,
}

impl Cancellation {
    /// Create an enabled signal for one independently cancellable operation.
    pub fn new() -> Self {
        Self {
            cancelled: Some(Arc::new(AtomicBool::new(false))),
        }
    }

    /// Whether an owner can request cancellation of this operation.
    pub fn is_enabled(&self) -> bool {
        self.cancelled.is_some()
    }

    /// Request cancellation. Completion is acknowledged when the worker returns.
    pub fn cancel(&self) {
        if let Some(cancelled) = &self.cancelled {
            cancelled.store(true, Ordering::Release);
        }
    }

    /// Fast cooperative checkpoint; cancellation is irreversible.
    pub fn is_cancelled(&self) -> bool {
        self.cancelled
            .as_ref()
            .is_some_and(|cancelled| cancelled.load(Ordering::Acquire))
    }
}

// This concrete registry avoids function-pointer accessors generated by
// thread_local!. Locks protect lookup/replacement only, never analysis work.
// The outermost scope removes its entry, so completed workers are not retained.
static SCOPES: Mutex<Vec<(ThreadId, Cancellation)>> = Mutex::new(Vec::new());

struct Restore {
    thread: ThreadId,
    previous: Option<Cancellation>,
}
impl Drop for Restore {
    fn drop(&mut self) {
        let mut scopes = SCOPES
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        if let Some(index) = scopes.iter().position(|(thread, _)| *thread == self.thread) {
            if let Some(previous) = self.previous.take() {
                scopes[index].1 = previous;
            } else {
                scopes.swap_remove(index);
            }
        }
    }
}

/// Run on this thread with a token, restoring the containing scope on exit.
pub fn with_cancellation<T>(token: &Cancellation, operation: impl FnOnce() -> T) -> T {
    let thread = std::thread::current().id();
    let previous = {
        let mut scopes = SCOPES
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        if let Some((_, current)) = scopes.iter_mut().find(|(owner, _)| *owner == thread) {
            Some(std::mem::replace(current, token.clone()))
        } else {
            scopes.push((thread, token.clone()));
            None
        }
    };
    let _restore = Restore { thread, previous };
    operation()
}

/// Current analysis token. Capturing it preserves its cancellation identity.
pub fn current_cancellation() -> Cancellation {
    let thread = std::thread::current().id();
    SCOPES
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .iter()
        .find(|(owner, _)| *owner == thread)
        .map(|(_, cancellation)| cancellation.clone())
        .unwrap_or_default()
}

